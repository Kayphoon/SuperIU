import AppKit
import XCTest
@testable import SuperClipboard

final class ClipboardTests: XCTestCase {
    private func temporaryDirectory() -> URL {
        FileManager.default.temporaryDirectory.appendingPathComponent("superiu-test-\(UUID().uuidString)")
    }

    private func cleanup(_ directory: URL) {
        guard FileManager.default.fileExists(atPath: directory.path) else { return }
        do { try FileManager.default.removeItem(at: directory) }
        catch { XCTFail("Failed to clean owned test directory: \(error)") }
        XCTAssertFalse(FileManager.default.fileExists(atPath: directory.path))
    }

    private func image(_ seed: Int = 0, width: Int = 512, height: Int = 256) throws -> CGImage {
        let context = try XCTUnwrap(CGContext(data: nil, width: width, height: height,
                                             bitsPerComponent: 8, bytesPerRow: 0,
                                             space: CGColorSpaceCreateDeviceRGB(),
                                             bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(NSColor(calibratedRed: CGFloat(seed % 256) / 255, green: 0.3,
                                     blue: 0.7, alpha: 1).cgColor)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return try XCTUnwrap(context.makeImage())
    }

    func testTextHistoryDeduplicatesAndEvictsLeastRecentAt200() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            for number in 0...200 { store.recordText("row \(number)") }
            store.recordText("row 1")
            XCTAssertEqual(store.entries.count, 200)
            XCTAssertEqual(store.entries.first?.text, "row 1")
            XCTAssertEqual(store.search("row 0").count, 0)
            XCTAssertFalse(FileManager.default.fileExists(atPath: directory.path))
        }
    }

    func testDefaultImagesKeep25ThumbnailsWithoutCreatingFiles() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            for number in 0...25 { try store.recordImage(image(number)) }
            XCTAssertEqual(store.entries.count, 25)
            XCTAssertTrue(store.entries.allSatisfy { $0.imageURL == nil })
            XCTAssertEqual(store.entries.first?.thumbnail?.width, 128)
            XCTAssertEqual(store.entries.first?.thumbnail?.height, 64)
            XCTAssertFalse(FileManager.default.fileExists(atPath: directory.path))
        }
    }

    func testExplicitImagePersistenceRestoresMetadataAndCleansOnOptOut() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let id = try XCTUnwrap(store.recordImage(image()))
            store.attachOCR("Hello 中文", to: id)
            let restored = try ClipboardStore(directory: directory)
            XCTAssertEqual(restored.search("中文").map(\.id), [id])
            XCTAssertNotNil(restored.entries.first?.imageURL)
            try restored.setImagePersistenceEnabled(false)
            XCTAssertFalse(FileManager.default.fileExists(atPath: directory.path))
            XCTAssertTrue(restored.entries.allSatisfy { $0.imageURL == nil })
        }
    }

    func testSensitivePasteboardsAreIgnoredIncludingMarkersOnAnotherItem() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType"] {
                pasteboard.clearContents()
                let secret = NSPasteboardItem()
                secret.setString("password", forType: .string)
                let metadata = NSPasteboardItem()
                metadata.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
                pasteboard.writeObjects([secret, metadata])
                monitor.poll()
            }
            XCTAssertEqual(store.entries.count, 0)
        }
    }

    func testMonitorDoesNotArchivePreexistingClipboardAndOwnCopiesDoNotDuplicate() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            pasteboard.setString("preexisting", forType: .string)
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            monitor.poll()
            XCTAssertEqual(store.entries.count, 0)
            let id = try monitor.copyImage(image())
            monitor.poll()
            XCTAssertEqual(store.entries.map(\.id), [try XCTUnwrap(id)])
            XCTAssertNotNil(pasteboard.data(forType: .png))
        }
    }

    func testMonitorArchivesOrdinaryExternalTextAndMovesDuplicatesToFront() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            for text in ["first", "second", "first"] {
                pasteboard.clearContents()
                pasteboard.setString(text, forType: .string)
                monitor.poll()
            }
            XCTAssertEqual(store.entries.compactMap(\.text), ["first", "second"])
        }
    }

    func testLateOCRCannotResurrectEvictedImageOrChangePasteboard() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            let id = try XCTUnwrap(monitor.copyImage(image()))
            for number in 1...25 { try store.recordImage(image(number)) }
            try monitor.copyText("newer clipboard")
            store.attachOCR("secret result", to: id)
            XCTAssertEqual(store.search("secret result").count, 0)
            XCTAssertEqual(pasteboard.string(forType: .string), "newer clipboard")
        }
    }

    func testUncachedImageRestoreFailsWithoutMutatingPasteboard() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let id = try XCTUnwrap(store.recordImage(image()))
            pasteboard.setString("untouched", forType: .string)
            XCTAssertThrowsError(try store.copy(id, to: pasteboard))
            XCTAssertEqual(pasteboard.string(forType: .string), "untouched")
        }
    }

    func testImageLRUEvictionDeletesOriginalsAndClearRemovesHistory() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let firstID = try XCTUnwrap(store.recordImage(image()))
            let firstURL = try XCTUnwrap(store.entries.first?.imageURL)
            for number in 1...25 { try store.recordImage(image(number)) }
            XCTAssertEqual(store.entries.count, 25)
            XCTAssertFalse(store.entries.contains { $0.id == firstID })
            XCTAssertFalse(FileManager.default.fileExists(atPath: firstURL.path))
            let cache = ImageDiskCache(directory: directory)
            XCTAssertLessThanOrEqual(try cache.bytes(), 50_000_000)
            try store.clear()
            XCTAssertEqual(store.entries.count, 0)
            XCTAssertEqual(try ClipboardStore(directory: directory).entries.count, 0)
        }
    }

    func testCacheBudgetEvictsActualLargeOriginals() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let first = try XCTUnwrap(store.recordImage(image()))
            let path = try XCTUnwrap(store.entries.first?.imageURL)
            // Simulate a previously cached high-entropy PNG's disk cost. The
            // production byte accounting, not compression in a fixture, owns eviction.
            let file = try FileHandle(forWritingTo: path)
            try file.truncate(atOffset: UInt64(43 * 1024 * 1024))
            try file.close()
            try store.recordImage(image(100))
            XCTAssertFalse(store.entries.contains { $0.id == first })
            XCTAssertFalse(FileManager.default.fileExists(atPath: path.path))
            XCTAssertLessThanOrEqual(try ImageDiskCache(directory: directory).bytes(), 50_000_000)
        }
    }
}
